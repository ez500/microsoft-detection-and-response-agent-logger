def make_rule_confidence_updated_event(
    rule_id: str, old_confidence: float, new_confidence: float,
    hit_count: int, last_triggered: Optional[str], source: str = "",
) -> AuditEvent:
    """Create a RULE_CONFIDENCE_UPDATED event."""
    delta = round(new_confidence - old_confidence, 4)
    return AuditEvent(
        event_type=EventType.RULE_CONFIDENCE_UPDATED,
        severity=Severity.INFO,
        source_file=source,
        details={
            "rule_id": rule_id,
            "old_confidence": old_confidence,
            "new_confidence": new_confidence,
            "delta": delta,
            "hit_count": hit_count,
            "last_triggered": last_triggered,
        },
        raw_snippet=f"Rule {rule_id} confidence: "
                    f"{old_confidence} → {new_confidence} "
                    f"({delta:+g}) after {hit_count} hits",
    )


