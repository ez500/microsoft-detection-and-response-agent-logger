def make_volume_spike_event(
    category: str, current_count: int, avg_count: float,
    threshold: float, source: str = "",
) -> AuditEvent:
    """Create a VOLUME_SPIKE_DETECTED anomaly event."""
    return AuditEvent(
        event_type=EventType.VOLUME_SPIKE_DETECTED,
        severity=Severity.WARNING,
        source_file=source,
        details={
            "category": category,
            "current_count": current_count,
            "rolling_avg_7d": round(avg_count, 1),
            "threshold": threshold,
            "deviation_pct": round(
                ((current_count - avg_count) / avg_count) * 100 if avg_count > 0 else 0, 1
            ),
        },
        raw_snippet=f"Volume spike: '{category}' alerts surged to {current_count} "
                    f"(7-day avg: {avg_count:.1f}, threshold: {threshold})",
    )


