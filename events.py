"""
events.py — Event taxonomy for the MXDR logging system.

Defines all detectable event types as dataclasses. Every event the scanner
extracts from analysis artifacts is represented here with a structured schema.
"""

from dataclasses import dataclass, field
from datetime import datetime
from enum import Enum
from typing import Any, Dict, List, Optional
from uuid import uuid4


class EventType(str, Enum):
    """Every event category that the logging system can detect."""

    # ── Ingestion ──────────────────────────────────────────────────────
    ALERTS_INGESTED = "ALERTS_INGESTED"

    # ── Pre-Analysis ───────────────────────────────────────────────────
    ANALYSIS_PACKET_GENERATED = "ANALYSIS_PACKET_GENERATED"

    # ── Correlation Rules ──────────────────────────────────────────────
    RULE_TRIGGERED = "RULE_TRIGGERED"
    RULE_NOT_TRIGGERED = "RULE_NOT_TRIGGERED"

    # ── Watchlist ──────────────────────────────────────────────────────
    WATCHLIST_HIT = "WATCHLIST_HIT"

    # ── Clustering ─────────────────────────────────────────────────────
    CLUSTERS_GENERATED = "CLUSTERS_GENERATED"

    # ── Prioritization ─────────────────────────────────────────────────
    SOC_QUEUE_GENERATED = "SOC_QUEUE_GENERATED"

    # ── Reporting ──────────────────────────────────────────────────────
    NARRATIVE_REPORT_WRITTEN = "NARRATIVE_REPORT_WRITTEN"

    # ── Rule Updates ───────────────────────────────────────────────────
    RULE_CONFIDENCE_UPDATED = "RULE_CONFIDENCE_UPDATED"
    RULE_RETIRED = "RULE_RETIRED"

    # ── Watchlist Updates ──────────────────────────────────────────────
    WATCHLIST_UPDATED = "WATCHLIST_UPDATED"

    # ── False Negatives ────────────────────────────────────────────────
    FALSE_NEGATIVE_RECORDED = "FALSE_NEGATIVE_RECORDED"

    # ── Statistics ─────────────────────────────────────────────────────
    DAILY_STATS_APPENDED = "DAILY_STATS_APPENDED"

    # ── Anomaly Detection ──────────────────────────────────────────────
    NEW_ALERT_TITLE_DETECTED = "NEW_ALERT_TITLE_DETECTED"
    VOLUME_SPIKE_DETECTED = "VOLUME_SPIKE_DETECTED"

    # ── Entity Insights ────────────────────────────────────────────────
    HIGH_RISK_ENTITY_OBSERVED = "HIGH_RISK_ENTITY_OBSERVED"

    # ── Pipeline Metadata ──────────────────────────────────────────────
    PIPELINE_RUN_STARTED = "PIPELINE_RUN_STARTED"
    PIPELINE_RUN_COMPLETED = "PIPELINE_RUN_COMPLETED"


class Severity(str, Enum):
    INFO = "INFO"
    WARNING = "WARNING"
    CRITICAL = "CRITICAL"


@dataclass
class AuditEvent:
    """
    Base audit event dataclass.

    Every event extracted by the scanner or generated by the logging system
    is represented as an instance of this class.
    """

    event_id: str = field(default_factory=lambda: uuid4().hex[:12])
    timestamp: str = field(default_factory=lambda: datetime.utcnow().isoformat() + "Z")
    event_type: EventType = EventType.PIPELINE_RUN_STARTED
    severity: Severity = Severity.INFO
    source_file: str = ""
    details: Dict[str, Any] = field(default_factory=dict)
    raw_snippet: str = ""
    llm_narrative: str = ""

    def to_dict(self) -> Dict[str, Any]:
        """Serialize to a plain dict for JSON output."""
        return {
            "event_id": self.event_id,
            "timestamp": self.timestamp,
            "event_type": self.event_type.value
            if isinstance(self.event_type, EventType)
            else self.event_type,
            "severity": self.severity.value
            if isinstance(self.severity, Severity)
            else self.severity,
            "source_file": self.source_file,
            "details": self.details,
            "raw_snippet": self.raw_snippet,
            "llm_narrative": self.llm_narrative,
        }

    @classmethod
    def from_dict(cls, d: Dict[str, Any]) -> "AuditEvent":
        """Deserialize from a plain dict."""
        return cls(
            event_id=d.get("event_id", ""),
            timestamp=d.get("timestamp", ""),
            event_type=EventType(d["event_type"]) if "event_type" in d else EventType.PIPELINE_RUN_STARTED,
            severity=Severity(d["severity"]) if "severity" in d else Severity.INFO,
            source_file=d.get("source_file", ""),
            details=d.get("details", {}),
            raw_snippet=d.get("raw_snippet", ""),
            llm_narrative=d.get("llm_narrative", ""),
        )


# ── Convenience factory functions ─────────────────────────────────────────────

def make_alert_ingestion_event(
    total: int, high: int, medium: int, low: int, info: int,
    incidents: int, source: str = "",
) -> AuditEvent:
    """Create an ALERTS_INGESTED event with severity breakdown."""
    return AuditEvent(
        event_type=EventType.ALERTS_INGESTED,
        severity=Severity.INFO,
        source_file=source,
        details={
            "total": total,
            "high": high,
            "medium": medium,
            "low": low,
            "informational": info,
            "incidents": incidents,
            "severity_breakdown": {
                "high": high,
                "medium": medium,
                "low": low,
                "informational": info,
            },
        },
        raw_snippet=f"Alerts ingested: {total} total "
                    f"(H:{high} M:{medium} L:{low} I:{info}) "
                    f"across {incidents} incidents",
    )


def make_packet_generated_event(
    date_str: str, stats: dict, rule_hits: dict,
    watchlist_hits: int, notable_count: int, source: str = "",
) -> AuditEvent:
    """Create an ANALYSIS_PACKET_GENERATED event."""
    triggered = {k: len(v) for k, v in rule_hits.items() if v}
    not_triggered = [k for k, v in rule_hits.items() if not v]
    return AuditEvent(
        event_type=EventType.ANALYSIS_PACKET_GENERATED,
        severity=Severity.INFO,
        source_file=source,
        details={
            "date": date_str,
            "stats": stats,
            "rules_triggered": triggered,
            "rules_not_triggered": not_triggered,
            "watchlist_hit_count": watchlist_hits,
            "notable_alert_count": notable_count,
        },
        raw_snippet=f"Analysis packet for {date_str}: "
                    f"{stats.get('total', 0)} alerts, "
                    f"triggered rules: {triggered}, "
                    f"{watchlist_hits} watchlist hits",
    )


def make_rule_triggered_event(
    rule_id: str, hits: List[Dict], source: str = "",
    confidence: Optional[float] = None,
) -> AuditEvent:
    """Create a RULE_TRIGGERED event for one correlation rule."""
    severity = Severity.WARNING if len(hits) > 0 else Severity.INFO
    return AuditEvent(
        event_type=EventType.RULE_TRIGGERED,
        severity=severity,
        source_file=source,
        details={
            "rule_id": rule_id,
            "hit_count": len(hits),
            "hits": hits,
            "confidence": confidence,
        },
        raw_snippet=f"Correlation rule {rule_id} triggered {len(hits)} time(s): "
                    f"{[h.get('alert_count', h.get('distinct_users', 1)) for h in hits[:5]]}",
    )


def make_rule_not_triggered_event(rule_id: str, source: str = "") -> AuditEvent:
    """Create a RULE_NOT_TRIGGERED event."""
    return AuditEvent(
        event_type=EventType.RULE_NOT_TRIGGERED,
        severity=Severity.INFO,
        source_file=source,
        details={"rule_id": rule_id},
        raw_snippet=f"Correlation rule {rule_id} checked — no hits found",
    )


