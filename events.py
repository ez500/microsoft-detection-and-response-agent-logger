def make_clusters_generated_event(
    clusters: List[Dict], source: str = "",
) -> AuditEvent:
    """Create a CLUSTERS_GENERATED event."""
    severities = [c.get("priority", "low") for c in clusters]
    p1_count = severities.count("P1")
    p2_count = severities.count("P2")
    p3_count = severities.count("P3")
    return AuditEvent(
        event_type=EventType.CLUSTERS_GENERATED,
        severity=Severity.WARNING if p1_count > 0 else Severity.INFO,
        source_file=source,
        details={
            "cluster_count": len(clusters),
            "p1_count": p1_count,
            "p2_count": p2_count,
            "p3_count": p3_count,
            "clusters": clusters,
        },
        raw_snippet=f"Generated {len(clusters)} suspicious clusters "
                    f"(P1:{p1_count} P2:{p2_count} P3:{p3_count})",
    )


def make_soc_queue_generated_event(
    items: List[Dict], source: str = "",
) -> AuditEvent:
    """Create a SOC_QUEUE_GENERATED event."""
    p1 = sum(1 for i in items if i.get("priority") == "P1")
    p2 = sum(1 for i in items if i.get("priority") == "P2")
    p3 = sum(1 for i in items if i.get("priority") == "P3")
    top_items = [i.get("title", i.get("incident_id", "")) for i in items[:5]]
    return AuditEvent(
        event_type=EventType.SOC_QUEUE_GENERATED,
        severity=Severity.CRITICAL if p1 > 0 else Severity.WARNING,
        source_file=source,
        details={
            "total_items": len(items),
            "p1_count": p1,
            "p2_count": p2,
            "p3_count": p3,
            "top_items": top_items,
        },
        raw_snippet=f"SOC queue generated: {len(items)} items "
                    f"(P1:{p1} P2:{p2} P3:{p3}) — top: {top_items}",
    )


